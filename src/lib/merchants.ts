/** All active merchants across all countries */
export const allMerchants: Merchant[] = MERCHANTS.filter((m) => m.isActive);

/** Get merchants filtered by country code (e.g. 'KE', 'NG') */
export function getMerchantsByCountry(countryCode: string): Merchant[] {
  return allMerchants.filter(
    (m) => m.countryCode.toUpperCase() === countryCode.toUpperCase(),
  );
}

/** Get merchants filtered by category */
export function getMerchantsByCategory(category: string): Merchant[] {
  return allMerchants.filter(
    (m) => m.category.toLowerCase() === category.toLowerCase(),
  );
}

/** Get a single merchant by ID */
export function getMerchantById(id: string): Merchant | undefined {
  return allMerchants.find((m) => m.id === id);
}

